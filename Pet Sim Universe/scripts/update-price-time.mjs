import { readFile, writeFile, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { normalizePrice } from '../server/pricing.js';

// Save an authoring time with the published prices. Page visits and unrelated
// builds must never become "price updates". The metadata travels with the ZIP.
function priceRevision(prices) {
  const rows = Object.entries(prices).flatMap(([category, items]) =>
    Object.entries(items).flatMap(([id, price]) => {
      const variants = price && typeof price === 'object' ? Object.entries(price) : [['normal', price]];
      return variants.map(([variant, value]) => [`${category}/${id}/${variant}`, normalizePrice(value).key]);
    })
  ).sort(([a], [b]) => a.localeCompare(b));
  return createHash('sha256').update(JSON.stringify(rows)).digest('hex');
}

function validTime(value) {
  return typeof value === 'string' && Number.isFinite(Date.parse(value));
}

async function committedPriceTime(root, revision) {
  try {
    const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    git(['ls-files', '--error-unmatch', '--', 'public/data/prices.js']);
    // A local change must not inherit the timestamp of the old committed file.
    git(['diff', 'HEAD', '--quiet', '--', 'public/data/prices.js']);
    const prefix = git(['rev-parse', '--show-prefix']);
    const pricePath = `${prefix}public/data/prices.js`;
    const history = git(['log', '--format=%H%x09%cI', '--', 'public/data/prices.js']);
    let timestamp = null;
    let previousChangeAt = null;
    // Cloudflare builds do not commit generated metadata. Walk the price-file
    // history so comment edits, equivalent numbers and reverts are dated right.
    for (const entry of history.split('\n').filter(Boolean)) {
      const [commit, committedAt] = entry.split('\t');
      if (!validTime(committedAt)) continue;
      let historicalRevision;
      try {
        const source = git(['show', `${commit}:${pricePath}`]);
        const historical = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
        historicalRevision = priceRevision(historical.PRICES);
      } catch { break; }
      if (historicalRevision !== revision) { previousChangeAt = new Date(committedAt).toISOString(); break; }
      timestamp = new Date(committedAt).toISOString();
    }
    return timestamp ? { updatedAt: timestamp, previousChangeAt } : null;
  } catch {
    return null;
  }
}

export async function updatePriceTime(root) {
  const pricePath = path.join(root, 'public/data/prices.js');
  const metadataPath = path.join(root, 'public/data/price-updates.js');
  const source = await readFile(pricePath, 'utf8');
  const sourceHash = createHash('sha256').update(source).digest('hex');
  const { PRICES } = await import(`${pathToFileURL(pricePath).href}?v=${sourceHash}`);
  const revision = priceRevision(PRICES);
  let previous = null;
  try {
    const saved = await readFile(metadataPath, 'utf8');
    previous = JSON.parse(saved.match(/export const PRICE_UPDATE = ([\s\S]*);\s*$/)[1]);
  } catch { /* First build, or metadata from before this feature. */ }

  let updatedAt = null;
  let timestampSource = 'unavailable';
  const committed = await committedPriceTime(root, revision);
  const recorded = previous?.revision === revision && validTime(previous.updatedAt);
  // Keep an imported authoring time through shallow clones and unrelated builds.
  // Still detect an A -> B -> A revert when Git proves B occurred after it.
  const revertedAfterRecording = recorded && committed?.previousChangeAt
    && Date.parse(committed.previousChangeAt) > Date.parse(previous.updatedAt);
  if (recorded && !revertedAfterRecording) {
    updatedAt = previous.updatedAt;
    timestampSource = previous.source;
  } else if (committed) {
    updatedAt = committed.updatedAt;
    timestampSource = 'git';
  } else if (previous?.revision && previous.revision !== revision) {
    updatedAt = (await stat(pricePath)).mtime.toISOString();
    timestampSource = 'file';
  }

  const metadata = { version: 1, revision, updatedAt, source: timestampSource };
  const output = `// Generated by scripts/update-price-time.mjs during npm run build. Do not edit.\nexport const PRICE_UPDATE = ${JSON.stringify(metadata, null, 2)};\n`;
  let existing = '';
  try { existing = await readFile(metadataPath, 'utf8'); } catch {}
  if (existing !== output) await writeFile(metadataPath, output);
  console.log(`Price update time: ${updatedAt || 'not recorded yet'} (${timestampSource}).`);
  return metadata;
}
